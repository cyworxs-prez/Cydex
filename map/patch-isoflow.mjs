// Vendor a patched copy of isoflow's dist bundle.
//
// isoflow 1.1.1 is unmaintained and its zoom story is broken in ways we cannot
// reach from the outside, because the uiState store lives behind a React
// context that is only readable from inside <Isoflow>'s own subtree:
//
//   1. The zoom +/- buttons have their `disabled` conditions swapped, so once
//      you reach 100% the zoom-out button greys out and you are stuck there.
//   2. incrementZoom/decrementZoom clamp to [0.2, 1], so you can never magnify
//      past native size - on a phone, where fit-to-view lands around 35%, that
//      is the difference between readable and not.
//   3. Every zoom/scroll change animates over 250ms, which is fine for a button
//      press and awful for a pinch: the map lags a quarter second behind your
//      fingers.
//
// Rather than fork the package we rewrite three exact strings in its shipped
// bundle. Each anchor must match EXACTLY ONCE or this script aborts - a silent
// no-op patch would leave the map subtly broken with no error, which is the
// failure mode we care about most.
//
//   node patch-isoflow.mjs   ->  vendor/isoflow.patched.js
//
// Re-run after any `npm install`. If isoflow is ever upgraded the anchors will
// stop matching and this will fail loudly; that is the intent.

import { readFileSync, writeFileSync, mkdirSync } from 'fs';

const SRC = 'node_modules/isoflow/dist/index.js';
const OUT = 'vendor/isoflow.patched.js';

const PATCHES = [
  {
    name: 'expose-uistate-store',
    why: 'publish the uiState store on window so our own zoom/pinch layer can '
       + 'drive isoflow\'s real zoom + scroll state instead of CSS-scaling a '
       + 'wrapper (which would desync isoflow\'s tile maths and make dragging '
       + 'pan at the wrong rate)',
    find: 'r.current||(r.current=ft(((e,t)=>({zoom:gt.xf.zoom,',
    repl: 'r.current||(window.__isoflowUiStore=r.current=ft(((e,t)=>({zoom:gt.xf.zoom,'
  },
  {
    name: 'instant-transform-during-gestures',
    why: 'let a gesture opt out of the 250ms tween so pinch and wheel zoom '
       + 'track 1:1 instead of trailing the fingers',
    find: 'duration:i||a?0:.25',
    repl: 'duration:i||a||window.__isoflowInstant?0:.25'
  },
  {
    name: 'drop-builtin-zoom-controls',
    why: 'the built-in control sits bottom-left of the renderer, underneath our '
       + 'phone control bar, and its buttons clamp to [0.2, 1] - mixing them '
       + 'with our wider range would make zoom jump. We render our own.',
    find: '[Tc.qe.EXPLORABLE_READONLY]:["ZOOM_CONTROLS","VIEW_TITLE"]',
    repl: '[Tc.qe.EXPLORABLE_READONLY]:["VIEW_TITLE"]'
  }
];

let src;
try {
  src = readFileSync(SRC, 'utf8');
} catch (err) {
  console.error(`FATAL: cannot read ${SRC} - run npm install first.`);
  process.exit(1);
}

for (const p of PATCHES) {
  const hits = src.split(p.find).length - 1;
  if (hits !== 1) {
    console.error(`FATAL: patch "${p.name}" matched ${hits} times, expected 1.`);
    console.error('       isoflow\'s bundle has changed. Re-derive the anchor');
    console.error(`       before shipping; do NOT skip the patch.`);
    process.exit(1);
  }
  src = src.replace(p.find, p.repl);
}

// Prove every replacement actually landed in the output we are about to write,
// rather than trusting that replace() did what we asked.
for (const p of PATCHES) {
  if (!src.includes(p.repl)) {
    console.error(`FATAL: patch "${p.name}" did not land in the output.`);
    process.exit(1);
  }
  if (src.includes(p.find)) {
    console.error(`FATAL: patch "${p.name}" left the original text behind.`);
    process.exit(1);
  }
}

mkdirSync('vendor', { recursive: true });
writeFileSync(OUT, '/* GENERATED by patch-isoflow.mjs - do not edit. */\n' + src);

console.log(`${OUT}: ${src.length} bytes`);
for (const p of PATCHES) console.log(`    applied  ${p.name}`);
